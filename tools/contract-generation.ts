import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { promisify } from "node:util";

const execute = promisify(execFile);
export const contractRoot = resolve(process.cwd(), "packages/contracts");
const binaryRoot = resolve(process.cwd(), "node_modules/.bin");
const environment = {
  ...process.env,
  PATH: `${binaryRoot}:${process.env.PATH ?? ""}`,
  GOTOOLCHAIN: "local",
  GOWORK: "off",
};
export const generatedArtifactPaths = [
  "src/features/protocol/contracts/gen/identity/v1/identity_pb.ts",
  "gen/go/identity/v1/identity.pb.go",
  "gen/go/identity/v1/identityv1connect/identity.connect.go",
].toSorted();

export const runContractCommand = async (
  command: string,
  args: readonly string[],
  cwd = contractRoot,
): Promise<string> => {
  const result = await execute(command, [...args], {
    cwd,
    env: environment,
    encoding: "utf8",
    timeout: 180_000,
    maxBuffer: 4 * 1024 * 1024,
  });
  return result.stdout.trim();
};

export const verifyContractTools = async (): Promise<void> => {
  assert.equal(await runContractCommand("buf", ["--version"]), "1.75.0", "Native Buf pin differs");
  assert.equal(
    await runContractCommand("protoc-gen-es", ["--version"]),
    "protoc-gen-es v2.17.0",
    "ES generator pin differs",
  );
  assert.equal(
    await runContractCommand("protoc-gen-go", ["--version"]),
    "protoc-gen-go v1.36.12",
    "Go generator pin differs",
  );
  assert.equal(
    await runContractCommand("protoc-gen-connect-go", ["--version"]),
    "1.21.1",
    "Connect generator pin differs",
  );
  assert.ok(
    (await runContractCommand("go", ["version"])).startsWith("go version go1.27.3 "),
    "Native Go pin differs",
  );
};

/** Remove only the pinned generator's forbidden file-wide suppression. */
const normalizeTypeScript = (source: string): string => {
  const header =
    '// @generated by protoc-gen-es v2.17.0 with parameter "target=ts,import_extension=js"\n' +
    "// @generated from file identity/v1/identity.proto (package identity.v1, syntax proto3)\n";
  const suppression = "/* eslint-disable */\n";
  assert.ok(
    source.startsWith(header + suppression),
    "Generated TypeScript preamble changed; review normalization",
  );
  assert.equal(source.split(suppression).length, 2, "Unexpected generated suppression count");
  return header + source.slice(header.length + suppression.length);
};

export const generateContractFiles = async (destination: string): Promise<void> => {
  await runContractCommand("buf", ["generate"], destination);
  const file = join(destination, "src/features/protocol/contracts/gen/identity/v1/identity_pb.ts");
  await writeFile(file, normalizeTypeScript(await readFile(file, "utf8")));
};
